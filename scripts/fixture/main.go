func text(im *image.RGBA, s string, x, y, scale int, c color.Color) {
	for _, r := range s {
		for row, line := range glyphs[r] {
			for col, p := range line {
				if p == '1' {
					draw.Draw(im, image.Rect(x+col*scale, y+row*scale, x+(col+1)*scale, y+(row+1)*scale), image.NewUniform(c), image.Point{}, draw.Src)
				}
			}
		}
		x += 6 * scale
	}
}
